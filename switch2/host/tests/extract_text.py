"""Writes the .text of an x86-64 ELF object as a C array plus symbol offsets (test guests).
Usage: python3 extract_text.py <in.o> <out.h> <array_name>"""
import struct
import sys


def main():
    src, dst, name = sys.argv[1:4]
    data = open(src, "rb").read()
    shoff, = struct.unpack_from("<Q", data, 0x28)
    shentsize, shnum, shstrndx = struct.unpack_from("<HHH", data, 0x3A)
    sections = [struct.unpack_from("<IIQQQQIIQQ", data, shoff + i * shentsize) for i in range(shnum)]
    strtab = sections[shstrndx]
    def sname(off):
        start = strtab[4] + off
        return data[start:data.index(b"\0", start)].decode()
    text_index = next(i for i, s in enumerate(sections) if sname(s[0]) == ".text")
    for s in sections:
        if sname(s[0]) == ".rela.text" and s[5]:
            sys.exit("guest code has relocations; pass everything through the api pointer")
    text = data[sections[text_index][4]:sections[text_index][4] + sections[text_index][5]]
    symtab = next(s for s in sections if s[1] == 2)
    symstr = sections[symtab[6]]
    out = ["/* generated by extract_text.py from %s */" % src.split("/")[-1],
           "static const unsigned char %s[] = {%s};" % (name, ",".join(str(b) for b in text))]
    for i in range(symtab[5] // 24):
        st_name, st_info, _, st_shndx, st_value, _ = struct.unpack_from("<IBBHQQ", data, symtab[4] + i * 24)
        if st_shndx == text_index and (st_info & 0xF) == 2 and (st_info >> 4) == 1:
            start = symstr[4] + st_name
            sym = data[start:data.index(b"\0", start)].decode()
            out.append("#define %s_%s %du" % (name, sym, st_value))
    open(dst, "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
